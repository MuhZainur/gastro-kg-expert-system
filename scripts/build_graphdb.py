"""Build the GraphDB artefacts from the rules and the engine.

graphdb/updates/*.ru           one SPARQL Update per rule; run in file-name order, one commit each
graphdb/gastrokg-inferred.ttl  the same results already materialised (import and visualise)

GraphDB did not reliably show the results of earlier rules to later ones when all rules
were sent as a single request, so every rule is its own request.

Run:  python scripts/build_graphdb.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from backend.app import engine  # noqa: E402

GRAPHDB = ROOT / "graphdb"
INFERRED_GRAPH = "urn:gastrokg:inferred"

def to_update(rule: engine.Rule) -> str:
    """Turn `CONSTRUCT { T } WHERE { P }` into `INSERT { GRAPH g { T } } WHERE { P }`."""
    match = re.search(r"CONSTRUCT\s*\{(?P<template>.*?)\}\s*WHERE\s*(?P<pattern>\{.*\})\s*$", rule.query, re.S)
    if not match:
        raise ValueError(f"unexpected shape of rule {rule.name}")
    return (f"INSERT {{ GRAPH <{INFERRED_GRAPH}> {{ {match['template'].strip()} }} }}\n"
            f"WHERE {match['pattern']}")


def update_file(rule: engine.Rule) -> str:
    note = "# Run repeatedly until GraphDB reports 0 added statements.\n" if rule.iterate else ""
    prefixes = "\n".join(line for line in rule.query.splitlines() if line.startswith("PREFIX "))
    return (f"# {rule.name}: {rule.title}\n# {rule.description}\n# iterate: {str(rule.iterate).lower()}\n"
            f"# GENERATED by scripts/build_graphdb.py\n{note}{prefixes}\n\n{to_update(rule)}\n")


if __name__ == "__main__":
    GRAPHDB.mkdir(exist_ok=True)
    rules = engine.load_rules()
    updates = GRAPHDB / "updates"
    updates.mkdir(exist_ok=True)
    for old in updates.glob("*.ru"):
        old.unlink()
    for rule in rules:
        (updates / f"{rule.name}.ru").write_text(update_file(rule), encoding="utf-8")
    result = engine.reason_all_cases()
    inferred = result.inferred
    inferred.bind("rdfs", "http://www.w3.org/2000/01/rdf-schema#")
    header = "# GastroKG: results of the SPARQL rules. GENERATED by scripts/build_graphdb.py\n"
    (GRAPHDB / "gastrokg-inferred.ttl").write_text(header + inferred.serialize(format="turtle"), encoding="utf-8")
    print(f"update files: {len(rules)}; inferred triples: {len(inferred)}")
    print("next: python scripts/graphdb_load.py   (loads GraphDB and checks it matches)")
